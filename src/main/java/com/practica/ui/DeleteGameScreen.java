    private void jButtonConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonConfirmarActionPerformed
        // TODO add your handling code here:
       Juego juegoSeleccionado = (Juego) jComboBox1.getSelectedItem();

        if (juegoSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Selecciona un joc per borrar.", "Avís", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 1. Validar si el juego tiene alquileres activos (no devueltos)
        boolean tieneAlquileresActivos = false;
        for (Alquiler a : DataStore.getAlquileres()) {
            if (a.getJuego().equals(juegoSeleccionado) && !a.isDevuelto()) {
                tieneAlquileresActivos = true;
                break;
            }
        }

        if (tieneAlquileresActivos) {
            JOptionPane.showMessageDialog(this, 
                "No es pot esborrar aquest joc perquè té lloguers actius pendents de retorn.", 
                "Operació No Permesa", 
                JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 2. Confirmación previa antes de eliminar
        int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "Estàs segur que vols esborrar el joc '" + juegoSeleccionado.getNombre() + "'?",
            "Confirmar eliminació",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (confirmacion == JOptionPane.YES_OPTION) {
            // 3. Eliminar de DataStore
            DataStore.getJuegos().remove(juegoSeleccionado);
            JOptionPane.showMessageDialog(this, "Joc esborrat amb èxit!");
            this.dispose();
        }
    }//GEN-LAST:event_jButtonConfirmarActionPerformed

