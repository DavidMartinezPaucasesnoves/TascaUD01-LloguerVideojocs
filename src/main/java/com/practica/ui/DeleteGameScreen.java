    private void cargarCombos() {
    ((javax.swing.JComboBox) jComboBox1).removeAllItems();
    for (Juego j : DataStore.getJuegos()) {
        ((javax.swing.JComboBox) jComboBox1).addItem(j);
    }
    actualizarDetalles();
}

private void actualizarDetalles() {
    Juego juego = (Juego) jComboBox1.getSelectedItem();
    if (juego != null) {
        // Género
        jLabelUtPC1.setText(juego.getGenero());

        // Unidades por plataforma
        jLabelPS5.setText(String.valueOf(juego.getStockPs5()));
        jLabelXbox.setText(String.valueOf(juego.getStockXbox()));
        jLabelPC.setText(String.valueOf(juego.getStockPc()));
        jLabelSwitch2.setText(String.valueOf(juego.getStockSwitch2()));
    } else {
        jLabelPC.setText("0");
        jLabelPS5.setText("0");
        jLabelXbox.setText("0");
        jLabelSwitch2.setText("0");
    }
}
    
    

